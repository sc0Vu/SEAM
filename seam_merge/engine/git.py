"""The git operations the engine needs, and nothing more.

Merges are built without touching any working tree: `merge-tree --write-tree` makes
the merged tree, `commit-tree` the merge commit, and `update-ref` publishes it with a
compare-and-swap. Hooks and fsmonitor are disabled on every call so no
repository-supplied code runs on the host (invariant 10).
"""

from __future__ import annotations

import io
import os
import re
import subprocess
import tarfile
from dataclasses import dataclass
from pathlib import Path

from seam_merge.engine.errors import GitError

_IDENT = re.compile(r"^([^<>\n]+?) *<([^<>\s]+)>$")
_EMAIL = re.compile(r"^[^<>\s]+$")


@dataclass(frozen=True)
class Identity:
    """A git identity, `Name <email>`. Neither part may contain `<`, `>`, a newline
    or other control character, so an identity can never inject a header or trailer."""

    name: str
    email: str

    def __post_init__(self) -> None:
        name_ok = bool(self.name) and self.name == self.name.strip() and not any(
            c in "<>" or ord(c) < 32 for c in self.name)
        if not (name_ok and _EMAIL.match(self.email)):
            raise ValueError(f"not a git identity: {self.name!r} <{self.email!r}>")

    def __str__(self) -> str:
        return f"{self.name} <{self.email}>"

    @classmethod
    def parse(cls, text: str) -> Identity:
        """`Name <email>` -> Identity; ValueError otherwise."""
        m = _IDENT.match(text.strip())
        if not m:
            raise ValueError(f"expected 'Name <email>', got {text!r}")
        return cls(m.group(1).strip(), m.group(2))


# SEAM makes every commit itself (agents never run git), so it is always the
# committer. The author is the human accountable for the run when one is known.
SEAM_IDENTITY = Identity("SEAM merge engine", "seam@localhost")


# Generated by running code, never authored: excluded from every staged diff.
ARTIFACT_EXCLUDES = ("**/__pycache__/**", "**/*.py[co]", "**/.pytest_cache/**")


@dataclass(frozen=True)
class MergeTree:
    """Result of a trial merge. `conflicts` empty means it merged textually clean."""

    tree: str
    conflicts: tuple[str, ...]


class GitRepo:
    """A git repository on the host. Paths and refs in, shas and booleans out.

    `author` is who commits made through this object are authored by (the operator
    who launched the run); None authors them as SEAM. The committer is always SEAM.
    """

    def __init__(self, path: str | Path, author: Identity | None = None) -> None:
        self.path = Path(path)
        self.author = author

    def _identity_env(self) -> dict:
        author = self.author or SEAM_IDENTITY
        return {"GIT_AUTHOR_NAME": author.name, "GIT_AUTHOR_EMAIL": author.email,
                "GIT_COMMITTER_NAME": SEAM_IDENTITY.name,
                "GIT_COMMITTER_EMAIL": SEAM_IDENTITY.email}

    def configured_identity(self) -> Identity | None:
        """`user.name <user.email>` as git config resolves it for this repo (repo,
        then global), or None if either is unset or not a valid identity."""
        name = self._run("config", "user.name").stdout.decode().strip()
        email = self._run("config", "user.email").stdout.decode().strip()
        try:
            return Identity(name, email) if name and email else None
        except ValueError:
            return None

    def _run(self, *args: str, input: bytes | None = None, env: dict | None = None):
        return subprocess.run(
            ["git", "-C", str(self.path), "-c", "core.hooksPath=/dev/null",
             "-c", "core.fsmonitor=false", *args],
            input=input, capture_output=True,
            env={**os.environ, **env} if env else None,
        )

    def _git(self, *args: str, **kw) -> str:
        proc = self._run(*args, **kw)
        if proc.returncode != 0:
            raise GitError(f"git {' '.join(args)}: {proc.stderr.decode().strip()}")
        return proc.stdout.decode().strip()

    def has_commit(self, ref: str) -> bool:
        """Whether `ref` names a commit; False for a branch with no commits yet (an
        empty repository's `main`) or a name that does not exist."""
        return self._run("rev-parse", "--verify", "-q", f"{ref}^{{commit}}").returncode == 0

    def rev_parse(self, ref: str) -> str:
        return self._git("rev-parse", "--verify", f"{ref}^{{commit}}")

    def merge_tree(self, base: str, branch: str) -> MergeTree:
        """Trial-merge `branch` into `base` with no working tree involved."""
        proc = self._run("merge-tree", "--write-tree", "--name-only", "--no-messages",
                         base, branch)
        if proc.returncode not in (0, 1):
            raise GitError(f"git merge-tree: {proc.stderr.decode().strip()}")
        lines = [ln for ln in proc.stdout.decode().splitlines() if ln]
        return MergeTree(tree=lines[0], conflicts=tuple(dict.fromkeys(lines[1:])))

    def commit_tree(self, tree: str, parents: list[str], message: str) -> str:
        args = ["commit-tree", tree, "-m", message]
        for p in parents:
            args += ["-p", p]
        return self._git(*args, env=self._identity_env())

    def export(self, commit: str, dest: Path) -> None:
        """Write `commit`'s files into `dest` — a plain tree, no `.git`, nothing for a
        sandboxed process to reach back into the repository through."""
        if not self._git("ls-tree", commit):  # an empty tree: nothing to write
            return
        proc = self._run("archive", "--format=tar", commit)
        if proc.returncode != 0:
            raise GitError(f"git archive: {proc.stderr.decode().strip()}")
        with tarfile.open(fileobj=io.BytesIO(proc.stdout)) as tar:
            tar.extractall(dest, filter="data")

    def is_ancestor(self, commit: str, ref: str) -> bool:
        """True if `commit` is reachable from `ref` (i.e. it has landed there)."""
        proc = self._run("merge-base", "--is-ancestor", commit, ref)
        if proc.returncode not in (0, 1):
            raise GitError(f"git merge-base: {proc.stderr.decode().strip()}")
        return proc.returncode == 0

    def update_branch(self, branch: str, new: str, expected: str) -> bool:
        """Atomically move `branch` from `expected` to `new`. False if it had moved."""
        return self._run("update-ref", f"refs/heads/{branch}", new, expected).returncode == 0

    def checked_out_in(self, branch: str) -> list[str]:
        """Working trees that have `branch` checked out."""
        out = self._git("worktree", "list", "--porcelain")
        trees, current = [], None
        for line in out.splitlines():
            if line.startswith("worktree "):
                current = line.removeprefix("worktree ")
            elif line == f"branch refs/heads/{branch}":
                trees.append(current)
        return trees

    def diff(self, base: str, branch: str) -> str:
        """Everything `branch` changed since it forked from `base` (`base...branch`)."""
        return self._git("diff", "--no-color", "--no-ext-diff", f"{base}...{branch}")

    def merge_base(self, a: str, b: str) -> str:
        return self._git("merge-base", a, b)

    def read_file(self, commit: str, path: str) -> bytes | None:
        """`path`'s content at `commit`, or None if it does not exist there."""
        proc = self._run("cat-file", "-e", f"{commit}:{path}")
        if proc.returncode != 0:
            return None
        return self._run("cat-file", "blob", f"{commit}:{path}").stdout

    def changed_files(self, base: str, branch: str) -> list[str]:
        out = self._git("diff", "--name-only", "--no-renames", f"{base}...{branch}")
        return [ln for ln in out.splitlines() if ln]

    def stage_all(self) -> str:
        """Stage every change in this (work)tree; return the staged diff ('' if none).

        Interpreter byproducts (`ARTIFACT_EXCLUDES`) are never staged, whatever the
        repo's .gitignore says: running tests writes them, they are not the worker's
        edits, and staging them would read as an out-of-scope change (invariant 3).
        """
        self._git("add", "-A", "--", ".", *(f":(exclude,glob){g}" for g in ARTIFACT_EXCLUDES))
        return self._git("diff", "--cached", "--no-color", "--no-ext-diff")

    def commit_staged(self, message: str) -> str:
        """Commit what is staged in this (work)tree (author `self.author`, committer
        SEAM); return the new HEAD."""
        self._git("commit", "-q", "--no-verify", "-m", message, env=self._identity_env())
        return self.rev_parse("HEAD")

    def current_branch(self) -> str | None:
        """The branch this (work)tree has checked out, or None if HEAD is detached."""
        proc = self._run("symbolic-ref", "-q", "--short", "HEAD")
        return proc.stdout.decode().strip() or None if proc.returncode == 0 else None

    def has_branch(self, branch: str) -> bool:
        return self._run("rev-parse", "--verify", "-q", f"refs/heads/{branch}").returncode == 0

    def add_worktree(self, path: Path, branch: str, start: str) -> None:
        """Create a task's isolated worktree (invariant 1) on a new `branch` from
        `start`, or on `branch` as it is if it already exists: a task resumed after a
        crash or a removed worktree keeps its commits."""
        if self.has_branch(branch):
            self._git("worktree", "add", str(path), branch)
        else:
            self._git("worktree", "add", "-b", branch, str(path), start)

    def delete_merged_branch(self, branch: str, into: str) -> bool:
        """Delete `branch` if every commit on it is already in `into`; return whether
        it was deleted. The ref is removed only if it has not moved meanwhile."""
        if not self.has_branch(branch):
            return False
        sha = self.rev_parse(branch)
        if not self.is_ancestor(sha, into):
            return False
        return self._run("update-ref", "-d", f"refs/heads/{branch}", sha).returncode == 0

    def remove_worktree(self, path: Path) -> None:
        self._git("worktree", "remove", "--force", str(path))
